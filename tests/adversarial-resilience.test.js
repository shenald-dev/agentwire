test('SecurityAuditor: handles circular object structures without crashing', () => {
  const circular = {
    apiKey: 'sk-proj-1234567890123456789012345678901234567890',
    meta: { env: 'production' }
  };
  circular.self = circular;
  circular.meta.parent = circular;

  assert.doesNotThrow(() => {
    const findings = SecurityAuditor.audit(circular);
    assert.ok(findings.length > 0, 'Should detect OpenAI key even in circular structure');
    assert.strictEqual(findings[0].category, 'secret_leak');
  });
});

test('SecretScrubber: handles circular references and preserves Date/Buffer/RegExp', () => {
  const now = new Date();
  const regex = /test-[0-9]+/i;
  const buf = Buffer.from('agentwire-buffer');

  const payload = {
    key: 'ghp_123456789012345678901234567890123456',
    created: now,
    pattern: regex,
    data: buf,
    nested: { count: 42 }
  };
  payload.self = payload;
  payload.nested.backref = payload;

  assert.doesNotThrow(() => {
    const res = SecretScrubber.redact(payload);
    assert.strictEqual(res.count, 1, 'Should redact GitHub PAT');
    assert.ok(res.redacted.key.includes('****[REDACTED]'));
    assert.strictEqual(res.redacted.created, now, 'Date instance must be preserved');
    assert.strictEqual(res.redacted.pattern, regex, 'RegExp instance must be preserved');
    assert.strictEqual(res.redacted.data, buf, 'Buffer instance must be preserved');
    assert.strictEqual(res.redacted.self, '[Circular]');
    assert.strictEqual(res.redacted.nested.backref, '[Circular]');
  });
});

test('LoopDetector: argument key ordering invariance (canonical sorting)', () => {
  const detector = new LoopDetector(2);

  // Call 1 with keys { a: 1, b: 2 }
  const call1 = {
    kind: 'tool_call',
    payload: { tool: 'search_db', arguments: { query: 'users', limit: 10 } }
  };
  // Call 2 with inverted keys { b: 2, a: 1 }
  const call2 = {
    kind: 'tool_call',
    payload: { tool: 'search_db', arguments: { limit: 10, query: 'users' } }
  };

  assert.strictEqual(detector.evaluate(call1), null);
  const alert = detector.evaluate(call2);
  assert.ok(alert, 'Should detect loop despite different argument key insertion order');
  assert.strictEqual(alert?.type, 'identical_repeat');
});

test('ChaosEngine: combined latency injection and fault simulation', async () => {
  const chaos = new ChaosEngine([
    { id: 'delay_rule', enabled: true, action: 'delay', delayMs: 25 },
    { id: 'error_rule', enabled: true, action: 'error', errorStatusCode: 503, errorMessage: 'Service Unavailable' }
  ]);

  const start = Date.now();
  const res = await chaos.evaluate('test_tool', { foo: 'bar' });
  const elapsed = Date.now() - start;

  assert.ok(elapsed >= 20, 'Should inject the artificial latency delay');
  assert.strictEqual(res.shouldIntercept, true, 'Fault should intercept after delay');
  assert.strictEqual(res.action, 'error');
  assert.strictEqual(res.errorResponse.code, 503);
  assert.strictEqual(res.delayMs, 25);
});

