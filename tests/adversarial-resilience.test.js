test('WebServer: prevents path traversal and returns 403 Forbidden', async () => {
  const session = new WireSession('path-traversal-test');
  const server = new WebServer({
    session,
    breakpointEngine: new BreakpointEngine(),
    port: 0
  });
  const actualPort = await server.start();

  try {
    const res = await new Promise((resolve, reject) => {
      http.get(`http://127.0.0.1:${actualPort}/../../package.json`, (response) => {
        let body = '';
        response.on('data', (c) => (body += c));
        response.on('end', () => resolve({ status: response.statusCode, body }));
      }).on('error', reject);
    });

    // Should return 403 Forbidden or 404 Not Found, NEVER 200 with package.json
    assert.notStrictEqual(res.status, 200);
    assert.strictEqual(res.body.includes('@shenald/agentwire'), false, 'Must not leak file content');
  } finally {
    await server.stop();
  }
});

test('HttpProxy: preserves base URL path when proxying upstream', async () => {
  let requestedPath = '';
  const upstream = http.createServer((req, res) => {
    requestedPath = req.url || '';
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ ok: true }));
  });
  await new Promise((r) => upstream.listen(0, '127.0.0.1', r));
  const upstreamPort = upstream.address().port;

  const session = new WireSession('base-url-test');
  const proxy = new HttpProxy({
    session,
    breakpointEngine: new BreakpointEngine(),
    targetUrl: `http://127.0.0.1:${upstreamPort}/api/v1`,
    listenPort: 0
  });
  const proxyPort = await proxy.start();

  try {
    await new Promise((resolve, reject) => {
      const req = http.request({
        hostname: '127.0.0.1',
        port: proxyPort,
        path: '/models',
        method: 'GET'
      }, (res) => {
        res.on('data', () => {});
        res.on('end', resolve);
      });
      req.on('error', reject);
      req.end();
    });

    assert.strictEqual(requestedPath, '/api/v1/models', 'Proxy must preserve targetUrl base path prefix');
  } finally {
    await proxy.stop();
    await new Promise((r) => upstream.close(r));
  }
});

test('HttpProxy: reassembles fragmented SSE chunks across TCP boundaries', async () => {
  const upstream = http.createServer((req, res) => {
    res.writeHead(200, {
      'Content-Type': 'text/event-stream',
      'Cache-Control': 'no-cache',
      Connection: 'keep-alive'
    });
    // Send split chunk 1: fragmented data line
    res.write('data: {"delta":');
    setTimeout(() => {
      // Send split chunk 2: completion of data line
      res.write(' "chunk_text"}\n\n');
      res.end();
    }, 20);
  });
  await new Promise((r) => upstream.listen(0, '127.0.0.1', r));
  const upstreamPort = upstream.address().port;

  const session = new WireSession('sse-test');
  const proxy = new HttpProxy({
    session,
    breakpointEngine: new BreakpointEngine(),
    targetUrl: `http://127.0.0.1:${upstreamPort}`,
    listenPort: 0
  });
  const proxyPort = await proxy.start();

  try {
    await new Promise((resolve, reject) => {
      const req = http.request({
        hostname: '127.0.0.1',
        port: proxyPort,
        path: '/stream',
        method: 'GET'
      }, (res) => {
        res.on('data', () => {});
        res.on('end', resolve);
      });
      req.on('error', reject);
      req.end();
    });

    const sseEvents = session.getEvents().filter((e) => e.summary === 'SSE Stream Chunk');
    assert.strictEqual(sseEvents.length, 1, 'Fragmented SSE stream should be reassembled into 1 chunk event');
    assert.strictEqual(sseEvents[0].payload?.delta, 'chunk_text');
  } finally {
    await proxy.stop();
    await new Promise((r) => upstream.close(r));
  }
});
