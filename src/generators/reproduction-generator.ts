/**
 * agentwire - Deterministic Test & Reproduction Generator
 * Converts recorded AI agent sessions into standalone, executable test suites
 * (supporting node:test and jest) for offline regression testing and bug reproduction.
 */

import { SerializedSession, WireEvent } from '../types.js';

export interface TestGeneratorOptions {
  runner?: 'node-test' | 'jest';
  testName?: string;
}

export class TestGenerator {
  public static generate(
    session: SerializedSession,
    options: TestGeneratorOptions = {}
  ): string {
    const runner = options.runner || 'node-test';
    const testTitle = options.testName || `Reproduction: ${session.agentName || session.sessionId}`;
    const events = session.events || [];

    // Pair up tool calls and tool results
    const toolInteractions: Array<{
      step: number;
      tool: string;
      arguments: any;
      result: any;
      isError: boolean;
    }> = [];

    const usedResultIndices = new Set<number>();

    for (let i = 0; i < events.length; i++) {
      const ev = events[i];
      if (ev.kind === 'tool_call') {
        const toolName = ev.payload?.tool || ev.payload?.name || 'unknown_tool';
        const args = ev.payload?.arguments || ev.payload?.args || {};

        // Find next unused matching tool_result
        let nextResult: WireEvent | undefined;
        for (let j = i + 1; j < events.length; j++) {
          if (events[j].kind === 'tool_result' && !usedResultIndices.has(j)) {
            usedResultIndices.add(j);
            nextResult = events[j];
            break;
          }
        }
        const resPayload = nextResult?.payload || { content: [{ type: 'text', text: 'ok' }] };
        const isError = Boolean(nextResult?.payload?.isError || ev.payload?.isError);

        toolInteractions.push({
          step: ev.stepIndex,
          tool: toolName,
          arguments: args,
          result: resPayload,
          isError
        });
      }
    }

    if (runner === 'node-test') {
      return this.generateNodeTest(testTitle, session, toolInteractions);
    } else {
      return this.generateJestTest(testTitle, session, toolInteractions);
    }
  }

  private static generateNodeTest(
    title: string,
    session: SerializedSession,
    interactions: Array<{ step: number; tool: string; arguments: any; result: any; isError: boolean }>
  ): string {
    const mocksJson = JSON.stringify(interactions, null, 2);
    const safeTitle = JSON.stringify(title);

    return `// Auto-generated by agentwire (https://github.com/shenald-dev/agentwire)
// Recorded Session: ${session.sessionId}
// Generated at: ${new Date().toISOString()}

import { test } from 'node:test';
import assert from 'node:assert/strict';

test(${safeTitle}, async () => {
  // Captured Tool Mock Interactions
  const recordedInteractions = ${mocksJson};

  assert.strictEqual(
    recordedInteractions.length,
    ${interactions.length},
    'Expected ${interactions.length} captured tool interactions'
  );

  const canonicalize = (obj) => {
    if (obj === null || typeof obj !== 'object') return obj;
    if (Array.isArray(obj)) return obj.map(canonicalize);
    const sorted = {};
    for (const key of Object.keys(obj).sort()) {
      sorted[key] = canonicalize(obj[key]);
    }
    return sorted;
  };

  // Virtual Mock Tool Dispatcher
  let callIdx = 0;
  const mockCallTool = async (name, args) => {
    if (callIdx < recordedInteractions.length && recordedInteractions[callIdx].tool === name) {
      const stepResult = recordedInteractions[callIdx].result;
      callIdx++;
      return stepResult;
    }
    const targetCanon = JSON.stringify(canonicalize(args));
    const match = recordedInteractions.find(
      (m) => m.tool === name && JSON.stringify(canonicalize(m.arguments)) === targetCanon
    );
    if (!match) {
      throw new Error(\`Unexpected tool call: \${name} with args \${JSON.stringify(args)}\`);
    }
    return match.result;
  };

  // Replay verification sequence
  for (const step of recordedInteractions) {
    const result = await mockCallTool(step.tool, step.arguments);
    assert.ok(result, \`Tool \${step.tool} returned valid result\`);
  }
});
`;
  }

  private static generateJestTest(
    title: string,
    session: SerializedSession,
    interactions: Array<{ step: number; tool: string; arguments: any; result: any; isError: boolean }>
  ): string {
    const mocksJson = JSON.stringify(interactions, null, 2);
    const safeTitle = JSON.stringify(title);

    return `// Auto-generated by agentwire (https://github.com/shenald-dev/agentwire)
// Recorded Session: ${session.sessionId}
// Generated at: ${new Date().toISOString()}

describe(${safeTitle}, () => {
  const recordedInteractions = ${mocksJson};

  it('replays captured tool trajectory faithfully', async () => {
    expect(recordedInteractions.length).toBe(${interactions.length});

    const canonicalize = (obj) => {
      if (obj === null || typeof obj !== 'object') return obj;
      if (Array.isArray(obj)) return obj.map(canonicalize);
      const sorted = {};
      for (const key of Object.keys(obj).sort()) {
        sorted[key] = canonicalize(obj[key]);
      }
      return sorted;
    };

    let callIdx = 0;
    const mockCallTool = jest.fn(async (name, args) => {
      if (callIdx < recordedInteractions.length && recordedInteractions[callIdx].tool === name) {
        const stepResult = recordedInteractions[callIdx].result;
        callIdx++;
        return stepResult;
      }
      const targetCanon = JSON.stringify(canonicalize(args));
      const match = recordedInteractions.find(
        (m) => m.tool === name && JSON.stringify(canonicalize(m.arguments)) === targetCanon
      );
      if (!match) {
        throw new Error(\`Unexpected tool call: \${name}\`);
      }
      return match.result;
    });

    for (const step of recordedInteractions) {
      const result = await mockCallTool(step.tool, step.arguments);
      expect(result).toBeDefined();
    }
  });
});
`;
  }
}
